"""Inventory Python chat tests and exact-name Rust counterparts; no provider calls.

This deliberately leaves differently named/grouped coverage pending: matching outputs or
similar test titles do not establish the per-name completion rule in the investigation.
"""
from __future__ import annotations

import argparse
import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / 'docs/evidence/slice-6-chat-test-inventory.md'
DEFERRED = {
    'test_live_cli_has_no_tools': 'Needs explicit authenticated provider acceptance.',
    'test_live_copilot_has_no_tools_and_still_answers': 'Needs explicit authenticated provider acceptance.',
}
DIFFERENCES = {
    'test_a_failed_creation_is_a_direct_message_without_git_output':
        'Rust withholds arbitrary Git diagnostics even when errors are allowed; backend logs hold the reason.',
    'test_slack_unanswered_message_loses_its_reaction_without_a_check_mark':
        'Unauthorized DM events are acknowledged and ignored before any reaction; authorized failed replies clear eyes without a check.',
}
INAPPLICABLE = {
    'test_start_chat_without_slack_libraries_leaves_the_backend_running':
        'Python optional-import behavior; Rust links its Slack transport at build time.',
}


def inventory() -> str:
    rust = {}
    for source in sorted((ROOT / 'app/crates/core/tests').glob('chat*.rs')):
        text = source.read_text(encoding='utf-8')
        for match in re.finditer(r'#\[(?:tokio::)?test\]\s*(?:async\s+)?fn\s+(test_\w+)', text):
            rust[match.group(1)] = source.relative_to(ROOT).as_posix()
    rows = []
    counts = {'named': 0, 'pending': 0, 'deferred': 0, 'inapplicable': 0}
    for source in sorted((ROOT / 'backend/tests').glob('test_chat*.py')):
        tree = ast.parse(source.read_text(encoding='utf-8'))
        for node in tree.body:
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) or not node.name.startswith('test_'):
                continue
            name = node.name
            if name in DEFERRED:
                state, evidence = 'deferred', DEFERRED[name]
            elif name in INAPPLICABLE:
                state, evidence = 'inapplicable', INAPPLICABLE[name]
            elif name in rust:
                state, evidence = 'named', f'[{rust[name]}](../../{rust[name]})'
                if name in DIFFERENCES:
                    evidence += ' ' + DIFFERENCES[name]
            else:
                state, evidence = 'pending', 'Named parity test or documented equivalence still required.'
            counts[state] += 1
            rows.append(f'| `{source.name}::{name}` | {state} | {evidence} |')
    header = [
        '# Slice 6 Python chat test inventory', '',
        'Generated by `python contract/audit_chat_tests.py`; `--check` rejects drift or pending local tests.', '',
        'Counts are test functions, not parametrized cases. `named` records an exact-name',
        'Rust test counterpart, not a claim of live Slack/provider acceptance. Existing grouped',
        'tests and 117 frozen reference cases remain useful evidence but do not close pending rows.', '',
        ', '.join(f'{state}: {count}' for state, count in counts.items()) + '.', '',
        '| Python test | Status | Rust counterpart / remaining work |',
        '| --- | --- | --- |',
    ]
    return '\n'.join(header + rows) + '\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = inventory()
    if args.check:
        if '| pending |' in expected:
            raise SystemExit('Local chat test migration has pending cases.')
        if not REPORT.exists() or REPORT.read_text(encoding='utf-8') != expected:
            raise SystemExit('Chat test inventory is stale; regenerate it.')
    else:
        REPORT.write_text(expected, encoding='utf-8')
    print(next(line for line in expected.splitlines() if line.startswith("named:")))


if __name__ == '__main__':
    main()
